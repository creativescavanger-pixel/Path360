function includesValue(values, value) {
  return !value || (values || []).includes(value)
}

export function getEcosystemRecordsByCountry(countryCode) {
  const safeCode = String(countryCode || '').trim().toUpperCase()
  if (!safeCode) return []

  return ECOSYSTEM_DIRECTORY.filter((record) => record.countryCode === safeCode)
}

export function getEcosystemCitiesByCountry(countryCode) {
  return [...new Set(getEcosystemRecordsByCountry(countryCode).map((record) => record.city))]
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b))
}

export function getEcosystemCoverageByCountry() {
  return ECOSYSTEM_DIRECTORY.reduce((coverage, record) => {
    coverage[record.countryCode] = (coverage[record.countryCode] || 0) + 1
    return coverage
  }, {})
}

export function getEcosystemDirectoryRecords({
  countryCode = '',
  city = '',
  supportType = '',
  stage = '',
  need = '',
  query = '',
} = {}) {
  const safeCountry = String(countryCode).trim().toUpperCase()
  const safeCity = String(city).trim().toLowerCase()
  const safeQuery = String(query).trim().toLowerCase()

  return ECOSYSTEM_DIRECTORY.filter((record) => {
    if (safeCountry && record.countryCode !== safeCountry) return false
    if (safeCity && record.city.toLowerCase() !== safeCity) return false
    if (!includesValue(record.supportTypes, supportType)) return false
    if (!includesValue(record.stages, stage)) return false
    if (!includesValue(record.needs, need)) return false

    if (!safeQuery) return true

    const haystack = [
      record.name,
      record.city,
      record.countryCode,
      record.countrySlug,
      record.description,
      ...(record.supportTypes || []),
      ...(record.stages || []),
      ...(record.needs || []),
    ]
      .join(' ')
      .toLowerCase()

    return haystack.includes(safeQuery)
  }).sort((a, b) => a.name.localeCompare(b.name))
}

export function getEcosystemLabel(value, options) {
  return options.find((option) => option.value === value)?.label || value
}